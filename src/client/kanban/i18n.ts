/** Both dictionaries, for the tests. */
export const DICTS: Record<Lang, Record<Key, string>> = { en: EN, fi: FI };

/** The language to use: the one picked in this browser, else the browser's own when it's Finnish, else English. */
export function pickLang(saved: string | null | undefined, browser: string | undefined): Lang {
  if (saved === 'fi' || saved === 'en') return saved;
  return (browser ?? '').toLowerCase().startsWith('fi') ? 'fi' : 'en';
}

function savedLang(): string | null {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage.getItem(LANG_KEY);
  } catch {
    return null;
  }
}

let current: Lang = pickLang(savedLang(), typeof navigator === 'undefined' ? undefined : navigator.language);
const listeners = new Set<() => void>();

export function lang(): Lang {
  return current;
}

/** Changes the language (remembered in this browser) and tells the views to redraw. */
export function setLang(l: Lang) {
  if (l === current) return;
  current = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    // storage blocked
  }
  listeners.forEach((fn) => fn());
}

export function onLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Fills {name} placeholders. */
export function format(text: string, vars: Record<string, string | number> = {}): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  return format(DICTS[current][key] ?? EN[key] ?? key, vars);
}

